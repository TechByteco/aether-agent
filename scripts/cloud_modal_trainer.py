"""
AETHER Serverless Cloud GPU Continuous Trainer (Modal.com)
===========================================================
Deploys a serverless GPU training pipeline on Modal.com (NVIDIA A10G / L4 GPU)
that trains AETHER LoRA adapters on synthetic trajectories generated by Claude/Gemini,
quantizes the checkpoint to GGUF, and exposes an automated training webhook.

How to run on Modal:
1. pip install modal
2. modal setup (authenticate with free/hobby/team Modal account)
3. modal run scripts/cloud_modal_trainer.py
4. Or deploy as 24/7 serverless webhook: modal deploy scripts/cloud_modal_trainer.py
"""

import os
import json
from pathlib import Path

try:
    import modal
except ImportError:
    modal = None

if modal:
    app = modal.App("aether-continuous-trainer")
    volume = modal.Volume.from_name("aether-model-checkpoints", create_if_missing=True)

    # Cloud GPU Image with Unsloth, PyTorch, llama.cpp, and HuggingFace
    trainer_image = (
        modal.Image.debian_slim(python_version="3.11")
        .pip_install(
            "torch>=2.2.0",
            "transformers>=4.45.0",
            "datasets>=2.19.0",
            "accelerate>=0.30.0",
            "peft>=0.11.0",
            "bitsandbytes>=0.43.0",
            "trl>=0.8.6",
            "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git",
            "huggingface_hub",
            "scipy",
            "fastapi",
        )
        .run_commands(
            "git clone --depth 1 https://github.com/ggerganov/llama.cpp.git /llama.cpp",
            "pip install -r /llama.cpp/requirements.txt",
        )
    )

    @app.function(
        image=trainer_image,
        gpu="A10G",  # High-throughput 24GB VRAM GPU
        timeout=1800,  # 30 min max execution time
        volumes={"/checkpoints": volume},
    )
    def train_aether_lora(training_jsonl_content: str, run_id: str = "auto_gen") -> dict:
        """
        Executes fast QLoRA fine-tuning on the uploaded dataset,
        saves LoRA adapters, and converts to GGUF in the persistent volume.
        """
        import torch
        from unsloth import FastLanguageModel
        from datasets import Dataset
        from trl import SFTTrainer
        from transformers import TrainingArguments

        print(f"🚀 [Modal GPU Trainer] Initializing LoRA fine-tuning for Run ID: {run_id}")

        # 1. Parse dataset
        lines = [json.loads(line) for line in training_jsonl_content.strip().split("\n") if line.strip()]
        print(f"📊 Loaded {len(lines)} training trajectories from Teacher-Student curriculum.")

        # 2. Load Base Model (Llama 3.2 3B Instruct)
        max_seq_length = 4096
        model, tokenizer = FastLanguageModel.from_pretrained(
            model_name="unsloth/Llama-3.2-3B-Instruct",
            max_seq_length=max_seq_length,
            load_in_4bit=True,
        )

        # 3. Configure LoRA
        model = FastLanguageModel.get_peft_model(
            model,
            r=16,
            target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
            lora_alpha=16,
            lora_dropout=0,
            bias="none",
            use_gradient_checkpointing="unsloth",
            random_state=3407,
        )

        # 4. Format Prompts with ChatML template
        formatted_texts = []
        for sample in lines:
            msgs = sample.get("messages", [])
            text = tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=False)
            formatted_texts.append(text)

        dataset = Dataset.from_dict({"text": formatted_texts})

        # 5. Train with SFTTrainer
        output_dir = f"/checkpoints/aether_{run_id}"
        trainer = SFTTrainer(
            model=model,
            tokenizer=tokenizer,
            train_dataset=dataset,
            dataset_text_field="text",
            max_seq_length=max_seq_length,
            packing=False,
            args=TrainingArguments(
                per_device_train_batch_size=2,
                gradient_accumulation_steps=4,
                warmup_steps=5,
                max_steps=len(lines) * 2,
                learning_rate=2e-4,
                fp16=not torch.cuda.is_bf16_supported(),
                bf16=torch.cuda.is_bf16_supported(),
                logging_steps=1,
                output_dir=output_dir,
                save_strategy="no",
            ),
        )

        train_result = trainer.train()
        print("✓ LoRA Training Completed Successfully!")

        # 6. Save LoRA weights
        lora_path = f"{output_dir}/lora_adapter"
        model.save_pretrained(lora_path)
        tokenizer.save_pretrained(lora_path)

        # 7. Convert LoRA to GGUF using llama.cpp
        gguf_path = f"{output_dir}/aether_adapter.gguf"
        import subprocess
        conv_cmd = [
            "python",
            "/llama.cpp/convert_lora_to_gguf.py",
            lora_path,
            "--outfile",
            gguf_path,
        ]
        res = subprocess.run(conv_cmd, capture_output=True, text=True)
        print("GGUF Conversion Output:", res.stdout)
        if res.returncode != 0:
            print("GGUF Conversion Error:", res.stderr)

        volume.commit()
        return {
            "status": "success",
            "run_id": run_id,
            "samples_trained": len(lines),
            "loss": train_result.training_loss,
            "gguf_location": gguf_path,
        }

    @app.function(image=trainer_image)
    @modal.web_endpoint(method="POST")
    def trigger_auto_training(payload: dict) -> dict:
        """
        Public webhook endpoint called by local AETHER daemon when
        N high-quality teacher-student samples are buffered.
        """
        dataset_content = payload.get("dataset_jsonl", "")
        run_name = payload.get("run_name", f"gen_{int(time.time())}")
        
        if not dataset_content:
            return {"error": "Missing dataset_jsonl in payload"}

        call = train_aether_lora.spawn(dataset_content, run_name)
        return {
            "message": "Cloud training job queued on serverless NVIDIA A10G GPU",
            "job_call_id": call.object_id,
            "run_name": run_name,
        }


def local_upload_and_train():
    """CLI trigger to upload local synthetic dataset and run cloud training."""
    if not modal:
        print("Modal is not installed. Install via `pip install modal` to trigger cloud training.")
        return

    data_file = Path("data/memory/training/synthetic_finetune_dataset.jsonl")
    if not data_file.exists():
        print(f"Error: {data_file} not found.")
        return

    content = data_file.read_text(encoding="utf-8")
    with modal.enable_output():
        with app.run():
            result = train_aether_lora.remote(content, "cli_manual_run")
            print("Training Result:", result)


if __name__ == "__main__":
    local_upload_and_train()
